"""Run and persist the first controlled synthetic challenger experiment."""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
sys.path.insert(0, str(ROOT))

from simple_challenger.harness import canonical_hash  # noqa: E402
from simple_challenger.synthetic_experiment import (  # noqa: E402
    EXPERIMENT_CONTRACT,
    EXPERIMENT_STATUS,
    REAL_DATA_TRAINING_STATUS,
    RIGHTS_STATUS,
    SCENARIOS,
    SEEDS,
    TOP_K,
    run_controlled_experiment,
)


def _write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _flatten_for_csv(record: dict) -> dict:
    return {
        "scenario": record["scenario"],
        "seed": record["seed"],
        "model": record["model"],
        "feature_mode": record["feature_mode"],
        "train_rows": record["train_rows"],
        "validation_rows": record["validation_rows"],
        "test_rows": record["test_rows"],
        "roc_auc": record["classification"]["roc_auc"],
        "pr_auc": record["classification"]["pr_auc"],
        "brier": record["classification"]["brier"],
        "brier_baseline": record["classification"]["baseline_brier"],
        "brier_skill": record["classification"]["brier_skill"],
        "top5_precision": record["ranking"]["5"]["precision_at_k"],
        "top5_relative_return": record["ranking"]["5"]["top_k_relative_return"],
        "top5_hit_rate": record["ranking"]["5"]["hit_rate"],
        "top5_rank_ic": record["ranking"]["5"]["rank_ic"],
        "top10_relative_return": record["ranking"]["10"]["top_k_relative_return"],
        "top20_relative_return": record["ranking"]["20"]["top_k_relative_return"],
        "prediction_hash": record["prediction_hash"],
    }


def _write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    columns = list(rows[0]) if rows else ["status"]
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=columns)
        writer.writeheader()
        writer.writerows(rows)


def _fmt(value) -> str:
    if isinstance(value, float):
        return f"{value:.6f}"
    return str(value)


def _scenario_table(summary: dict) -> str:
    lines = [
        "| Scenario | Model | ROC-AUC mean | Top-5 synthetic relative return mean | Rank IC mean |",
        "|---|---:|---:|---:|---:|",
    ]
    for key, metrics in summary["by_scenario_model"].items():
        scenario, model = key.split("|", 1)
        lines.append(
            f"| {scenario} | {model} | {_fmt(metrics['roc_auc']['mean'])} | "
            f"{_fmt(metrics['top5_relative']['mean'])} | {_fmt(metrics['rank_ic']['mean'])} |"
        )
    return "\n".join(lines)


def _report(payload: dict) -> str:
    summary = payload["summary"]
    manifest = payload["manifest"]
    sizes = sorted({(item["scenario"], item["seed"], item["rows"]) for item in manifest["dataset_hashes"]})
    size_text = ", ".join(f"{scenario}/{seed}: {rows}" for scenario, seed, rows in sizes[:6]) + " ..."
    return f"""# NextGen First Controlled Synthetic Challenger Experiment Report

## 1. Executive summary

The first controlled Simple Challenger experiment completed using synthetic data only.  The pipeline exercised deterministic/reference, logistic regression, random forest, and gradient boosting adapters across six preregistered scenarios and five preregistered seeds.  Classification: `{payload['classification']}`.

## 2. Experiment purpose

This experiment validates the synthetic research pipeline mechanics: synthetic generation, PIT-safe features, chronological splitting, deterministic model fitting, predictions, cross-sectional ranking, synthetic economic evaluation, baseline-relative comparison, stability analysis, and immutable-style evidence.

## 3. Explicit synthetic-only statement

All training and evaluation rows were generated by `{manifest['generator_identity']}`.  No NSE/NIFTY/Stage 4A.3/Stage 5D/Stage 6/live/MCP/official-market data was used for model training.

## 4. Rights status

Real-data training status remains `{RIGHTS_STATUS}` and real-data training remains `{REAL_DATA_TRAINING_STATUS}`.

## 5. Experiment ID

`{payload['experiment_id']}`

Contract: `{EXPERIMENT_CONTRACT}`

## 6. Scenario definitions

{chr(10).join(f'- `{key}`: {value}' for key, value in SCENARIOS.items())}

## 7. Dataset sizes

Each scenario/seed generated compact synthetic panels.  Sample row counts: {size_text}

## 8. Temporal partitions

The experiment used strict chronological TRAIN, VALIDATION, and FINAL TEST boundaries with a five-session embargo.  No shuffled/random split was used and fold disjointness was enforced.

## 9. Model configurations

The only model families were deterministic/reference baseline, logistic regression, random forest, and gradient boosting.  Configurations were predefined; no hyperparameter search or final-test tuning was performed.

## 10. Seed set

Predeclared seeds: `{SEEDS}`.

## 11. Ranking methodology

Models were evaluated as cross-sectional rankers using deterministic score-descending ranking with `security_id` tie-breaks.  Top-K settings: `{TOP_K}`.

## 12. Predictive metrics

Metrics include ROC-AUC, PR-AUC, Brier score, Brier baseline, Brier skill, IC, Rank IC, and Precision@K where mathematically defined.

## 13. Economic synthetic metrics

Synthetic-only Top-K average forward return, benchmark-relative Top-K return, and hit-rate style metrics were computed.  These are synthetic research metrics only and are not expected market return, real alpha, or live profitability.

## 14. Baseline-relative results

Each challenger was compared on identical observations, temporal boundaries, labels, benchmarks, cost assumptions, and missing-data rules.  The population-equality guard remained active.

## 15. Scenario-by-scenario results

{_scenario_table(summary)}

## 16. Seed stability

The summary artifact reports mean, median, min, max, standard deviation, valid runs, and undefined runs for each scenario/model metric.  Superiority is treated as diagnostic synthetic evidence only.

## 17. Null-scenario false-positive analysis

Null scenario result: `{summary['null_scenario_result']}`.  Persistent strong superiority in the no-signal scenario was {'detected and classified as a warning' if summary['null_false_positive_warning'] else 'not detected by the preregistered warning rule'}.

## 18. Ablation results

A small ablation compared the full minimal feature set against signal-bearing features removed.  Conclusion: `{summary['ablation']['conclusion']}`.  Mean full-minus-ablated Top-5 synthetic relative return delta: `{_fmt(summary['ablation']['mean_top5_relative_delta_full_minus_ablated'])}`.

## 19. Reproducibility results

Reproducibility result: `{summary['reproducibility']}`.  The experiment ID is deterministically derived from the complete experiment configuration.

## 20. Failures/undefined metrics

Failure records: `{len(payload['failures'])}`.  Undefined metrics are represented explicitly in result artifacts rather than fabricated.

## 21. Limitations

This is synthetic-only.  It validates research plumbing under controlled assumptions but does not validate a real-market model, real data rights, real execution, or production profitability.

## 22. Scientific interpretation

Observed behavior is interpreted as pipeline diagnostic evidence.  The null scenario is a false-positive control; linear, nonlinear, regime-shift, weak-signal, and adversarial scenarios probe plausible behavior without requiring a specific model to win.

## 23. Things this experiment DOES prove

- The Simple Challenger pipeline can run deterministic synthetic experiments across the four simple families.
- Chronological splitting, ranking, metrics, ablation, and compact evidence generation work under synthetic controls.
- Real-data training remains blocked.

## 24. Things this experiment DOES NOT prove

- It does not prove market alpha.
- It does not prove production readiness.
- It does not justify promotion of a challenger.
- It does not grant real-data training rights.

## 25. Frozen-lane integrity

No Stage 4A.3, Stage 5D, or Stage 6 modifications are required or authorized by this experiment.

## 26. Rights/provenance status

Rights status remains `{RIGHTS_STATUS}`.  Synthetic provenance is bound in the manifest and dataset hashes.

## 27. Recommended next research step

Review the synthetic evidence and, if acceptable, design a separate bounded next step.  Do not begin real-data training until rights status changes from `LICENSE_REQUIRED`.
"""


def main() -> None:
    payload = run_controlled_experiment()
    compact_records = [_flatten_for_csv(record) for record in payload["run_records"]]
    results_artifacts = {
        "manifest": "nextgen_synthetic_challenger_exp1_manifest.json",
        "summary": "nextgen_synthetic_challenger_exp1_summary.json",
        "run_results": "nextgen_synthetic_challenger_exp1_results.csv",
        "ablation": "nextgen_synthetic_challenger_exp1_ablation.json",
    }
    _write_csv(RESULTS / results_artifacts["run_results"], compact_records)
    _write_json(RESULTS / results_artifacts["summary"], {
        "artifact_type": "NEXTGEN_SYNTHETIC_CHALLENGER_EXP1_SUMMARY_V1",
        "experiment_id": payload["experiment_id"],
        "classification": payload["classification"],
        "summary": payload["summary"],
        "failures": payload["failures"],
        "synthetic_only": True,
        "rights_status": RIGHTS_STATUS,
        "real_data_training": REAL_DATA_TRAINING_STATUS,
    })
    _write_json(RESULTS / results_artifacts["ablation"], {
        "artifact_type": "NEXTGEN_SYNTHETIC_CHALLENGER_EXP1_ABLATION_V1",
        "experiment_id": payload["experiment_id"],
        "records": payload["ablation_records"],
        "summary": payload["summary"]["ablation"],
    })
    manifest = payload["manifest"]
    manifest["result_artifact_hashes"] = {
        name: canonical_hash(json.loads((RESULTS / file).read_text(encoding="utf-8"))) if file.endswith(".json")
        else canonical_hash((RESULTS / file).read_text(encoding="utf-8"))
        for name, file in results_artifacts.items() if name != "manifest"
    }
    manifest["experiment_manifest_hash"] = canonical_hash({key: value for key, value in manifest.items() if key != "experiment_manifest_hash"})
    _write_json(RESULTS / results_artifacts["manifest"], manifest)
    report = _report({**payload, "manifest": manifest})
    (ROOT / "NextGen_First_Synthetic_Challenger_Experiment_Report.md").write_text(report, encoding="utf-8")
    print(json.dumps({
        "experiment_id": payload["experiment_id"],
        "classification": payload["classification"],
        "scenarios": len(SCENARIOS),
        "seeds": len(SEEDS),
        "runs": len(payload["run_records"]),
        "failures": len(payload["failures"]),
        "rights_status": RIGHTS_STATUS,
        "real_data_training": REAL_DATA_TRAINING_STATUS,
        "status": "PASS",
    }, sort_keys=True))


if __name__ == "__main__":
    main()
